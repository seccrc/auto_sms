def clear(conn):
    marks = ",".join("?" * len(DEMO_PHONES))
    n = conn.execute(f"DELETE FROM messages WHERE phone_number IN ({marks})", DEMO_PHONES).rowcount
    conn.commit()
    print(f"가상 데이터 {n}건을 삭제했습니다.")


def seed(conn):
    now = datetime.now()
    total_in = total_out = 0
    for days_ago, hour, phone_idx, name, body, status, manual, receipt, replies in DEMO:
        when = (now - timedelta(days=days_ago)).replace(hour=hour, minute=(phone_idx * 7) % 60, second=0, microsecond=0)
        phone = DEMO_PHONES[phone_idx]
        cur = conn.execute(
            "INSERT INTO messages (phone_number, contact_name, body, direction, msg_time, dedup_key, created_at, status, manual_input, receipt_no) "
            "VALUES (?,?,?,'in',?,?,?,?,?,?)",
            (phone, name, body, when.strftime("%H:%M"),
             make_dedup_key(phone, body, when.strftime("%Y-%m-%d %H:%M")),
             when.strftime("%Y-%m-%d %H:%M:%S"), status, manual, receipt),
        )
        complaint_id = cur.lastrowid
        # 민원 자신을 스레드 앵커로 삼는다(app.py의 api_send()와 같은 규칙) —
        # 이렇게 해야 답신이 항상 이 민원 밑에 정확히 붙는다.
        conn.execute("UPDATE messages SET thread_id=? WHERE id=?", (complaint_id, complaint_id))
        total_in += 1
        for i, (reply_body, auto) in enumerate(replies, start=1):
            reply_at = when + timedelta(minutes=12 * i)
            conn.execute(
                "INSERT INTO messages (phone_number, contact_name, body, direction, dedup_key, created_at, auto_sent, thread_id) "
                "VALUES (?,?,?,'out',NULL,?,?,?)",
                (phone, name, reply_body, reply_at.strftime("%Y-%m-%d %H:%M:%S"), auto, complaint_id),
            )
            total_out += 1
    conn.commit()
    print(f"가상 민원 {total_in}건, 답신 {total_out}건을 넣었습니다.")
    print("확인이 끝나면 지우세요:  python seed_demo_data.py --clear")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clear", action="store_true", help="넣었던 가상 데이터를 지웁니다")
    args = parser.parse_args()

    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    if args.clear:
        clear(conn)
    else:
        clear(conn)  # 여러 번 실행해도 중복되지 않게 먼저 비우고 다시 넣는다
        seed(conn)
    conn.close()
